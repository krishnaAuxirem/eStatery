export const formatPrice = (price: number, priceUnit?: string): string => {
  if (price >= 10000000) {
    return `₹${(price / 10000000).toFixed(1)} Cr`;
  } else if (price >= 100000) {
    return `₹${(price / 100000).toFixed(1)} L`;
  } else {
    return `₹${price.toLocaleString("en-IN")}${priceUnit ? "/" + priceUnit : ""}`;
  }
};
